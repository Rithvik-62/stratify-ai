SELECT Product_ID, SUM(Revenue) AS REVENUE
FROM NOVAKART_DB.ANALYTICS.SALES
GROUP BY Product_ID
ORDER BY REVENUE DESC;

-- Q5: Products Generating Highest Profit
SELECT Product_ID, SUM(Profit) AS PROFIT
FROM NOVAKART_DB.ANALYTICS.SALES
GROUP BY Product_ID
ORDER BY PROFIT DESC;

-- Q6: Customers Generating Highest Revenue
SELECT Customer_ID, SUM(Revenue) AS REVENUE
FROM NOVAKART_DB.ANALYTICS.SALES
GROUP BY Customer_ID
ORDER BY REVENUE DESC;

-- Q7: Branches Generating Highest Revenue
SELECT Branch, SUM(Revenue) AS REVENUE
FROM NOVAKART_DB.ANALYTICS.SALES
GROUP BY Branch
ORDER BY REVENUE DESC;

-- Q8: Branches Generating Highest Profit
SELECT Branch, SUM(Profit) AS PROFIT
FROM NOVAKART_DB.ANALYTICS.SALES
GROUP BY Branch
ORDER BY PROFIT DESC;

-- Q9: Products with Low Inventory (Current_Stock < Minimum_Stock)
SELECT Inventory_ID, Product_ID, Warehouse, Current_Stock, Minimum_Stock
FROM NOVAKART_DB.ANALYTICS.INVENTORY
WHERE Current_Stock < Minimum_Stock;

-- Q10: Warehouses with Critical Stock
SELECT Warehouse, COUNT(*) AS CRITICAL_STOCK_COUNT
FROM NOVAKART_DB.ANALYTICS.INVENTORY
WHERE Stock_Status = 'Critical'
GROUP BY Warehouse
ORDER BY CRITICAL_STOCK_COUNT DESC;

-- Q11: Average Customer Order Value
SELECT ZEROIFNULL(ROUND(AVG(Revenue), 2)) AS AVG_CUSTOMER_ORDER_VALUE
FROM NOVAKART_DB.ANALYTICS.SALES;

-- Q12: Employees with Highest Performance Scores
SELECT Employee_ID, Name, Department, Role, Performance_Score, Salary
FROM NOVAKART_DB.ANALYTICS.EMPLOYEES
ORDER BY Performance_Score DESC, Salary DESC;

-- Q13: Total Finance Revenue, Expenses, Tax, and Net Profit
SELECT 
    SUM(Revenue) AS TOTAL_FINANCE_REVENUE,
    SUM(Expenses) AS TOTAL_FINANCE_EXPENSES,
    SUM(Tax) AS TOTAL_FINANCE_TAX,
    SUM(Net_Profit) AS TOTAL_FINANCE_NET_PROFIT
FROM NOVAKART_DB.ANALYTICS.FINANCE;

-- Q14: Percentage of Inventory Below Minimum Stock
SELECT ZEROIFNULL(ROUND((COUNT(CASE WHEN Current_Stock < Minimum_Stock THEN 1 END) / NULLIF(COUNT(*), 0)) * 100, 2)) AS PCT_BELOW_MINIMUM_STOCK
FROM NOVAKART_DB.ANALYTICS.INVENTORY;

-- Q15: Key Strategic Business Insights
-- (Summary Query: Combining Sales Performance & Inventory Risk)
SELECT 
    'Sales Revenue' AS METRIC, CAST(SUM(Revenue) AS VARCHAR) AS VALUE FROM NOVAKART_DB.ANALYTICS.SALES
UNION ALL
SELECT 'Sales Profit', CAST(SUM(Profit) AS VARCHAR) FROM NOVAKART_DB.ANALYTICS.SALES
UNION ALL
SELECT 'Low Stock Alert Items', CAST(COUNT(*) AS VARCHAR) FROM NOVAKART_DB.ANALYTICS.INVENTORY WHERE Current_Stock < Minimum_Stock
UNION ALL
SELECT 'Top Employee Performance Count (Score=5)', CAST(COUNT(*) AS VARCHAR) FROM NOVAKART_DB.ANALYTICS.EMPLOYEES WHERE Performance_Score = 5;

-- ============================================================================
-- PHASE 5: EXECUTIVE SUMMARY VIEW
-- ============================================================================

CREATE OR REPLACE VIEW NOVAKART_DB.ANALYTICS.VW_EXECUTIVE_SUMMARY AS
SELECT 
    s.TOTAL_REVENUE,
    s.TOTAL_PROFIT,
    s.PROFIT_MARGIN_PCT,
    s.SALES_COUNT,
    s.AVG_ORDER_VALUE,
    c.CUSTOMER_COUNT,
    p.PRODUCT_COUNT,
    e.EMPLOYEE_COUNT,
    i.INVENTORY_ITEM_COUNT,
    i.CRITICAL_STOCK_COUNT,
    i.LOW_STOCK_COUNT
FROM 
    (SELECT 
        SUM(Revenue) AS TOTAL_REVENUE,
        SUM(Profit) AS TOTAL_PROFIT,
        ZEROIFNULL(ROUND((SUM(Profit) / NULLIF(SUM(Revenue), 0)) * 100, 2)) AS PROFIT_MARGIN_PCT,
        COUNT(*) AS SALES_COUNT,
        ZEROIFNULL(ROUND(AVG(Revenue), 2)) AS AVG_ORDER_VALUE
     FROM NOVAKART_DB.ANALYTICS.SALES) s
CROSS JOIN
    (SELECT COUNT(*) AS CUSTOMER_COUNT FROM NOVAKART_DB.ANALYTICS.CUSTOMERS) c
CROSS JOIN
    (SELECT COUNT(*) AS PRODUCT_COUNT FROM NOVAKART_DB.ANALYTICS.PRODUCTS) p
CROSS JOIN
    (SELECT COUNT(*) AS EMPLOYEE_COUNT FROM NOVAKART_DB.ANALYTICS.EMPLOYEES) e
CROSS JOIN
    (SELECT 
        COUNT(*) AS INVENTORY_ITEM_COUNT,
        COUNT(CASE WHEN Stock_Status = 'Critical' THEN 1 END) AS CRITICAL_STOCK_COUNT,
        COUNT(CASE WHEN Current_Stock < Minimum_Stock THEN 1 END) AS LOW_STOCK_COUNT
     FROM NOVAKART_DB.ANALYTICS.INVENTORY) i;

