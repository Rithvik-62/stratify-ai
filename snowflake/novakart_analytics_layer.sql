-- Q1: Total Revenue
SELECT SUM(Revenue) AS TOTAL_REVENUE FROM NOVAKART_DB.ANALYTICS.SALES;

-- Q2: Total Profit
SELECT SUM(Profit) AS TOTAL_PROFIT FROM NOVAKART_DB.ANALYTICS.SALES;

-- Q3: Overall Profit Margin (%)
SELECT ZEROIFNULL(ROUND((SUM(Profit) / NULLIF(SUM(Revenue), 0)) * 100, 2)) AS OVERALL_PROFIT_MARGIN_PCT 
FROM NOVAKART_DB.ANALYTICS.SALES;

